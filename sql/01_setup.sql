-- Compute (warehouse) is separate from stored data.
CREATE WAREHOUSE IF NOT EXISTS LEARN_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE LEARN_WH;

CREATE DATABASE IF NOT EXISTS LEARN_DB;
CREATE SCHEMA IF NOT EXISTS LEARN_DB.RETAIL;
USE SCHEMA LEARN_DB.RETAIL;

CREATE OR REPLACE FILE FORMAT ORDERS_CSV
  TYPE = CSV
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  SKIP_HEADER = 1
  EMPTY_FIELD_AS_NULL = TRUE;

CREATE OR REPLACE STAGE ORDERS_STAGE
  FILE_FORMAT = ORDERS_CSV;

CREATE OR REPLACE TABLE ORDERS (
  order_id NUMBER,
  customer VARCHAR,
  amount NUMBER(10, 2),
  ordered_at DATE
);
