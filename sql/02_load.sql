USE WAREHOUSE LEARN_WH;
USE SCHEMA LEARN_DB.RETAIL;

-- Run from this repo folder in SnowSQL. The path is the CSV on your PC.
PUT file://data/orders.csv @ORDERS_STAGE AUTO_COMPRESS=TRUE OVERWRITE=TRUE;

COPY INTO ORDERS
  FROM @ORDERS_STAGE
  FILE_FORMAT = (FORMAT_NAME = ORDERS_CSV)
  ON_ERROR = 'ABORT_STATEMENT'
  PURGE = FALSE;

LIST @ORDERS_STAGE;
SELECT * FROM ORDERS ORDER BY order_id;
